const values = new Map();

Object.defineProperty(global, 'localStorage', {
  configurable: true,
  value: {
    clear() {
      values.clear();
    },
    getItem(key) {
      return values.has(key) ? values.get(key) : null;
    },
    removeItem(key) {
      values.delete(key);
    },
    setItem(key, value) {
      values.set(key, String(value));
    },
  },
});
