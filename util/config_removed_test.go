func writeRemovedSettingsConfig(t *testing.T, name, body string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), name)
	require.NoError(t, os.WriteFile(p, []byte(body), 0o600))
	return p
}

func readRemovedSettings(t *testing.T, path string) []string {
	t.Helper()
	file, err := os.Open(path)
	require.NoError(t, err)
	defer file.Close()
	previous := Config
	Config = &ConfigType{}
	defer func() { Config = previous }()
	names, err := decodeConfigDocument(file, path)
	require.NoError(t, err)
	return names
}

func clearRemovedProcessEnv(t *testing.T) {
	t.Helper()
	for _, name := range removedProcessEnvVars() {
		unsetTestEnv(t, name)
	}
}

func TestRemovedProcessSettingsInFile(t *testing.T) {
	tests := []struct {
		name     string
		file     string
		body     string
		expected []string
	}{
		{
			name:     "json uid and gid",
			file:     "config.json",
			body:     `{"dialect": "sqlite", "process": {"uid": 1001, "gid": 1002}}`,
			expected: []string{"process.gid", "process.uid"},
		},
		{
			name:     "json every setting",
			file:     "config.json",
			body:     `{"process": {"user": "semaphore", "chroot": "/jail", "no_new_privs": true, "app_namespaces": {"pid": true, "mount": false}}}`,
			expected: []string{"process.app_namespaces.pid", "process.chroot", "process.no_new_privs", "process.user"},
		},
		{
			name:     "yaml",
			file:     "config.yaml",
			body:     "dialect: sqlite\nprocess:\n  user: semaphore\n  app_namespaces:\n    user: true\n",
			expected: []string{"process.app_namespaces.user", "process.user"},
		},
		{
			name:     "yml extension",
			file:     "config.yml",
			body:     "process:\n  chroot: /jail\n",
			expected: []string{"process.chroot"},
		},
		{
			name:     "key in another case",
			file:     "config.json",
			body:     `{"Process": {"UID": 1001}}`,
			expected: []string{"process.UID"},
		},
		{
			name:     "duplicate process objects retain earlier legacy values",
			file:     "config.json",
			body:     `{"process":{"user":"runner","app_namespaces":{"pid":true}},"Process":{"app_namespaces":{"mount":true}}}`,
			expected: []string{"process.app_namespaces.mount", "process.app_namespaces.pid", "process.user"},
		},
		{
			name:     "duplicate namespace null retains legacy struct values",
			file:     "config.json",
			body:     `{"process":{"app_namespaces":{"pid":true}},"process":{"app_namespaces":null}}`,
			expected: []string{"process.app_namespaces.pid"},
		},
		{
			name:     "unknown setting is conservatively rejected",
			file:     "config.yaml",
			body:     "process:\n  future_restriction: true\n",
			expected: []string{"process.future_restriction"},
		},
		{
			name: "no section",
			file: "config.json",
			body: `{"dialect": "sqlite"}`,
		},
		{
			name: "null section",
			file: "config.json",
			body: `{"process": null}`,
		},
		{
			name: "empty section",
			file: "config.json",
			body: `{"process": {"app_namespaces": {}}}`,
		},
		{
			name: "only values that restricted nothing",
			file: "config.json",
			body: `{"process": {"user": "", "uid": 0, "chroot": "", "no_new_privs": false, "app_namespaces": {"pid": false}}}`,
		},
		{
			name: "empty yaml section",
			file: "config.yaml",
			body: "dialect: sqlite\nprocess: {}\n",
		},
		{
			name: "trailing data after the json document",
			file: "config.json",
			body: "{\"dialect\": \"sqlite\"}\n# generated by setup\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			p := writeRemovedSettingsConfig(t, tt.file, tt.body)

			file, err := os.Open(p)
			require.NoError(t, err)
			defer file.Close()
			previous := Config
			Config = &ConfigType{}
			t.Cleanup(func() { Config = previous })
			found, err := decodeConfigDocument(file, p)

			require.NoError(t, err)
			assert.Equal(t, tt.expected, found)
		})
	}
}

func TestRemovedProcessSettingsInFile_Unreadable(t *testing.T) {
	tests := []struct {
		name string
		path func(t *testing.T) string
	}{
		{"missing file", func(t *testing.T) string { return filepath.Join(t.TempDir(), "config.json") }},
		{"invalid uid type", func(t *testing.T) string {
			return writeRemovedSettingsConfig(t, "config.json", `{"process":{"uid":"1001"}}`)
		}},
		{"invalid process type", func(t *testing.T) string { return writeRemovedSettingsConfig(t, "config.json", `{"process":""}`) }},
		{"broken json", func(t *testing.T) string { return writeRemovedSettingsConfig(t, "config.json", `{"process": `) }},
		{"broken yaml", func(t *testing.T) string { return writeRemovedSettingsConfig(t, "config.yaml", "process: [") }},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			p := tt.path(t)
			file, err := os.Open(p)
			if err == nil {
				defer file.Close()
				previous := Config
				Config = &ConfigType{}
				t.Cleanup(func() { Config = previous })
				_, err = decodeConfigDocument(file, p)
			}
			assert.Error(t, err)
		})
	}
}

func TestRemovedProcessSettingsInEnv(t *testing.T) {
	tests := []struct {
		name     string
		env      map[string]string
		expected []string
	}{
		{
			name:     "uid and gid",
			env:      map[string]string{"SEMAPHORE_PROCESS_UID": "1001", "SEMAPHORE_PROCESS_GID": "1002"},
			expected: []string{"SEMAPHORE_PROCESS_UID", "SEMAPHORE_PROCESS_GID"},
		},
		{
			name:     "flags",
			env:      map[string]string{"SEMAPHORE_PROCESS_NO_NEW_PRIVS": "true", "SEMAPHORE_PROCESS_APP_NS_PID": "yes"},
			expected: []string{"SEMAPHORE_PROCESS_NO_NEW_PRIVS", "SEMAPHORE_PROCESS_APP_NS_PID"},
		},
		{
			name:     "user and chroot",
			env:      map[string]string{"SEMAPHORE_PROCESS_USER": "semaphore", "SEMAPHORE_PROCESS_CHROOT": "/jail"},
			expected: []string{"SEMAPHORE_PROCESS_USER", "SEMAPHORE_PROCESS_CHROOT"},
		},
		{
			name:     "literal string identities",
			env:      map[string]string{"SEMAPHORE_PROCESS_USER": "0", "SEMAPHORE_PROCESS_CHROOT": "false"},
			expected: []string{"SEMAPHORE_PROCESS_USER", "SEMAPHORE_PROCESS_CHROOT"},
		},
		{
			name: "values that restricted nothing",
			env: map[string]string{
				"SEMAPHORE_PROCESS_USER":         "",
				"SEMAPHORE_PROCESS_UID":          "0",
				"SEMAPHORE_PROCESS_NO_NEW_PRIVS": "False",
				"SEMAPHORE_PROCESS_APP_NS_PID":   " false ",
			},
		},
		{
			name: "nothing set",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			clearRemovedProcessEnv(t)
			for name, value := range tt.env {
				setTestEnv(t, name, value)
			}

			assert.Equal(t, tt.expected, removedProcessSettingsInEnv())
		})
	}
}

func TestCheckRemovedProcessSettings(t *testing.T) {
	t.Run("clean file and environment", func(t *testing.T) {
		clearRemovedProcessEnv(t)
		p := writeRemovedSettingsConfig(t, "config.json", `{"dialect": "sqlite", "process": {}}`)

		assert.NoError(t, checkRemovedProcessSettings(readRemovedSettings(t, p), &p))
	})

	t.Run("no config file", func(t *testing.T) {
		clearRemovedProcessEnv(t)

		assert.NoError(t, checkRemovedProcessSettings(nil, nil))
	})

	t.Run("file and environment are both named", func(t *testing.T) {
		clearRemovedProcessEnv(t)
		setTestEnv(t, "SEMAPHORE_PROCESS_NO_NEW_PRIVS", "true")
		p := writeRemovedSettingsConfig(t, "config.json", `{"process": {"uid": 1001, "gid": 1002}}`)

		err := checkRemovedProcessSettings(readRemovedSettings(t, p), &p)

		require.Error(t, err)
		assert.ErrorContains(t, err, "no longer supported")
		assert.ErrorContains(t, err, "process.uid (config file "+p+")")
		assert.ErrorContains(t, err, "process.gid (config file "+p+")")
		assert.ErrorContains(t, err, "SEMAPHORE_PROCESS_NO_NEW_PRIVS (environment variable)")
		assert.ErrorContains(t, err, "privileges of the Semaphore process")
	})

	t.Run("environment alone, without a config file", func(t *testing.T) {
		clearRemovedProcessEnv(t)
		setTestEnv(t, "SEMAPHORE_PROCESS_USER", "semaphore")

		err := checkRemovedProcessSettings(nil, nil)

		assert.ErrorContains(t, err, "SEMAPHORE_PROCESS_USER (environment variable)")
	})

}

func TestLoadConfigFileChecksSameDocument(t *testing.T) {
	for _, tc := range []struct{ name, body string }{
		{"config.json", `{"port":8123,"process":{"user":"runner"}}`},
		{"config.yaml", "port: 8123\nprocess:\n  user: runner\n"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			previous := Config
			Config = &ConfigType{}
			t.Cleanup(func() { Config = previous })
			p := writeRemovedSettingsConfig(t, tc.name, tc.body)
			used, names := loadConfigFile(p)
			require.NotNil(t, used)
			assert.Equal(t, p, *used)
			assert.Equal(t, ListenPort("8123"), Config.Port)
			assert.Equal(t, []string{"process.user"}, names)
		})
	}
}
